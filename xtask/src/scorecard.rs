//! Scorecard generation: measure the workspace and write `docs/scorecard.md`.
//!
//! `cargo xtask scorecard` regenerates the file from the current tree and the recorded perf baseline.

use std::fmt::Write as _;
use std::process::ExitCode;

const OUTPUT: &str = "docs/scorecard.md";

/// Regenerate `docs/scorecard.md`.
pub fn run() -> ExitCode {
    let crates = count_dirs("crates");
    let apps = count_dirs("apps");
    let mut files = 0usize;
    let mut lines = 0usize;
    for root in ["crates", "apps", "xtask/src"] {
        collect_rust(root, &mut files, &mut lines);
    }
    let commands = count_occurrences("crates/engine/src", "CommandSpec::new(");

    let baseline = crate::perf::read_baseline();
    let budgets = crate::perf::read_budgets();

    let mut out = String::new();
    let _ = writeln!(out, "# Scorecard\n");
    let _ = writeln!(out, "Generated by `cargo xtask scorecard` from the current tree and the perf baseline. Numbers are measured, not estimated.\n");
    let _ = writeln!(out, "## Workspace\n");
    let _ = writeln!(out, "| Metric | Value |");
    let _ = writeln!(out, "|---|---|");
    let _ = writeln!(out, "| Crates | {crates} |");
    let _ = writeln!(out, "| Apps | {apps} |");
    let _ = writeln!(out, "| Command specs (engine) | {commands} |");
    let _ = writeln!(out, "| Rust files | {files} |");
    let _ = writeln!(out, "| Rust lines | {lines} |");

    let _ = writeln!(out, "\n## Performance\n");
    if baseline.is_empty() {
        let _ = writeln!(out, "No baseline recorded — run `cargo xtask perf`.\n");
    } else {
        let _ = writeln!(out, "| Scenario | Measured (ms) | Budget (ms) |");
        let _ = writeln!(out, "|---|---|---|");
        for (name, ms) in &baseline {
            let budget = budgets.budgets.get(name).map(|value| format!("{value:.0}")).unwrap_or_else(|| "—".to_string());
            let _ = writeln!(out, "| {name} | {ms:.1} | {budget} |");
        }
        let _ = writeln!(out, "\nBudgets enforced: {} (`perf/budgets.toml`).", budgets.enforce);
    }

    let _ = writeln!(out, "\n## Correctness\n");
    let _ = writeln!(out, "- `cargo xtask ci` runs layers, fmt, clippy `-D warnings` and the full test suite.");
    let _ = writeln!(
        out,
        "- GPU compositor output is validated against an independent CPU reference; the BVH against brute force; export against re-import; `.sccraft` against a byte/file round-trip."
    );

    if let Some(parent) = std::path::Path::new(OUTPUT).parent()
        && let Err(err) = std::fs::create_dir_all(parent)
    {
        eprintln!("scorecard: could not create {}: {err}", parent.display());
        return ExitCode::FAILURE;
    }
    if let Err(err) = std::fs::write(OUTPUT, out) {
        eprintln!("scorecard: could not write {OUTPUT}: {err}");
        return ExitCode::FAILURE;
    }
    println!("wrote {OUTPUT} ({crates} crates, {commands} commands)");
    ExitCode::SUCCESS
}

fn count_dirs(root: &str) -> usize {
    std::fs::read_dir(root).map(|entries| entries.filter_map(Result::ok).filter(|entry| entry.path().is_dir()).count()).unwrap_or(0)
}

fn collect_rust(path: &str, files: &mut usize, lines: &mut usize) {
    let Ok(entries) = std::fs::read_dir(path) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_rust(&path.to_string_lossy(), files, lines);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            *files += 1;
            if let Ok(contents) = std::fs::read_to_string(&path) {
                *lines += contents.lines().count();
            }
        }
    }
}

fn count_occurrences(root: &str, needle: &str) -> usize {
    let mut count = 0usize;
    let Ok(entries) = std::fs::read_dir(root) else { return 0 };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            count += count_occurrences(&path.to_string_lossy(), needle);
        } else if path.extension().is_some_and(|ext| ext == "rs")
            && let Ok(contents) = std::fs::read_to_string(&path)
        {
            count += contents.matches(needle).count();
        }
    }
    count
}
